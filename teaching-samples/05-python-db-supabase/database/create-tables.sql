-- The database of the Supabase samples (modules 05, 06 and 07).
--
-- Supabase is a cloud service built around the PostgreSQL DBMS.
-- Run this script once, in the SQL Editor of your Supabase project.

create table public.country (
    country_id  bigint generated by default as identity primary key,
    created_at  timestamp with time zone not null default now(),
    name        text not null,
    code        text not null
);

create table public.actor (
    actor_id       bigint generated by default as identity primary key,
    created_at     timestamp with time zone not null default now(),
    last_name      text not null,
    first_name     text null,
    date_of_birth  date null,
    country_id     bigint null,

    constraint actor_country_id_fkey foreign key (country_id) references public.country (country_id)
);

-- A function that joins the two tables. Supabase offers every function of the
-- database as an address of its Data API:  /rest/v1/rpc/get_actors_with_country
create or replace function public.get_actors_with_country()
returns table (
    actor_id       bigint,
    last_name      text,
    first_name     text,
    country_id     bigint,
    country_name   text,
    country_code   text,
    date_of_birth  date
)
language sql
stable
as $$
    select a.actor_id, a.last_name, a.first_name, a.country_id,
           c.name as country_name, c.code as country_code, a.date_of_birth
    from public.actor a
         left join public.country c on a.country_id = c.country_id
    order by a.actor_id;
$$;


-- WHO MAY USE THE DATA
--
-- Every Supabase project has two kinds of keys:
--   the publishable key - for programs that anybody can look into (web pages, mobile apps),
--   the secret key      - for programs that run on a server which we control.
-- Our Python programs run on a server, so they use the secret key.

-- Row level security is switched on and no policy is defined: with the publishable key
-- nothing can be read or changed. Only the secret key (the role service_role) gets through.
alter table public.country enable row level security;
alter table public.actor enable row level security;

grant select, insert, update, delete on table public.country to service_role;
grant select, insert, update, delete on table public.actor to service_role;

revoke execute on function public.get_actors_with_country() from public, anon, authenticated;
grant execute on function public.get_actors_with_country() to service_role;


